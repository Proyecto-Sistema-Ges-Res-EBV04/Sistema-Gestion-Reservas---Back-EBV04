CREATE TABLE IF NOT EXISTS public.diaexcepcion
(
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1 ),
    fecha date NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    horainicio time without time zone NOT NULL,
    horafin time without time zone NOT NULL,
    rangohora integer NOT NULL,
    idsedeservicio integer NOT NULL,
    CONSTRAINT diaexcepcion_pkey PRIMARY KEY (id),
    CONSTRAINT fk_diaexcepcion_sedeservicio FOREIGN KEY (idsedeservicio)
        REFERENCES public.sedeservicio (id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,
    CONSTRAINT diaexcepcion_check CHECK (horafin > horainicio)
)

TABLESPACE pg_default;

